const nombres = new Intl.DisplayNames(["es"], { type: "region" });

export const PAISES: Pais[] = DATOS.split(" ")
  .map((d) => ({
    codigo: d.slice(0, 2).toLowerCase(),
    nombre: nombres.of(d.slice(0, 2)) ?? d.slice(0, 2),
    prefijo: `+${d.slice(2)}`,
  }))
  .sort((a, b) => a.nombre.localeCompare(b.nombre, "es"));

export const buscarPais = (codigo: string) => PAISES.find((p) => p.codigo === codigo);
